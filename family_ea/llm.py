"""The single structured-output call per message. The LLM understands; code executes.

Six kinds of output besides the reply: items (things and where they are), events
(things that happen at a time or on a day and then pass), todos (things to do, with a
deadline day or none), projects (names that group the todos), dreams (what the family
wants some day: no date, one shared list)
and reminders (a message to send someone at a given moment); plus `today`, a member's «на
сьогодні» board, and `notes`, the family's one
reference page («Нотатки»): all free text, replaced whole, only when asked. What happened,
stories, chatter are not kept: the bot answers and does not promise to write them down (a
journal of notes by day lived 2026-09-11..12 and went; the page came on 2026-09-13).
"""

from __future__ import annotations

import base64
import logging
from dataclasses import dataclass
from typing import Any, Literal, Protocol

from anthropic import AsyncAnthropic
from pydantic import BaseModel, Field

log = logging.getLogger(__name__)


# Op fields are never `X | None`: every nullable field makes the structured-output grammar
# bigger, and with several kinds of ops the API rejects the schema («compiled grammar is
# too large»). '' and 0 mean «not given», a lone '-' clears an optional field; ops.py
# treats them so.
class ItemOp(BaseModel):
    op: Literal["create", "update", "remove"]
    id: int = Field(default=0, description="update/remove: id існуючої речі з контексту")
    name: str = Field(
        default="",
        description="create/update: коротка назва, як її називають: «Паспорт Олі», «Мерч 2025»",
    )
    owner: str = Field(
        default="", description="чия річ, ім'я як у повідомленні (дитина теж); null — спільна"
    )
    place: str = Field(
        default="",
        description="грубе місце (Квартира, Офіс, Будинок батьків), з великої літери, як у"
        " відомих місцях, якщо є",
    )
    spot: str = Field(
        default="", description="де саме в цьому місці: «сейф», «білий комод на другому поверсі»"
    )
    note: str = Field(
        default="",
        description=(
            "щоб упізнати річ: варіант, що всередині, стан; не місце й не довідка; «-» прибирає"
        ),
    )


class EventOp(BaseModel):
    op: Literal["create", "update", "cancel"]
    id: int = Field(default=0, description="update/cancel: id існуючої події")
    text: str = Field(default="", description="create/update: що відбувається")
    who: str = Field(
        default="", description="id людини, кого це стосується, або null, якщо всієї сім'ї"
    )
    starts_at: str = Field(
        default="",
        description="початок події з часом, ISO 8601 з offset, напр. 2026-09-11T10:00:00+03:00",
    )
    until: str = Field(
        default="", description="кінець події з часом, ISO 8601 з offset; null, якщо невідомий"
    )
    date_from: str = Field(default="", description="цілоденна подія: перший день, YYYY-MM-DD")
    date_to: str = Field(
        default="", description="цілоденна подія: останній день включно, YYYY-MM-DD"
    )


class TodoOp(BaseModel):
    op: Literal["create", "update", "close"]
    id: int = Field(default=0, description="update/close: id існуючої задачі")
    text: str = Field(default="", description="create/update: що треба зробити")
    owner: str = Field(
        default="", description="id людини (oleh, anna) або null, якщо обидва чи неясно"
    )
    due: str = Field(
        default="",
        description="день задачі, YYYY-MM-DD; порожньо — не міняти; «-» прибрати",
    )
    status: Literal["done", "dropped", ""] = Field(
        default="", description="close: done — зроблено, dropped — більше не актуально"
    )
    project: str = Field(
        default="",
        description="create/update: id проєкту з контексту (названого, а для нової задачі —"
        " і підібраного за змістом) або назва проєкту з цього ж повідомлення; порожньо — не"
        " міняти; «-» прибрати з проєкту",
    )


# A project is a name that groups todos; nothing else to it, so create / update / close.
# `todos` moves existing todos in with the same op: «створи проєкт X і перенеси туди A і B»
# is one op, after the model created projects and claimed to have moved todos without a
# single todo update (2026-09-14, in production).
class ProjectOp(BaseModel):
    op: Literal["create", "update", "close"]
    id: int = Field(default=0, description="update/close: id існуючого проєкту")
    name: str = Field(
        default="", description="create: назва проєкту, коротко; update: нова назва, якщо міняють"
    )
    todos: list[int] = Field(
        default_factory=list,
        description="create/update: id наявних задач із контексту, які перенести в цей проєкт",
    )


class DreamOp(BaseModel):
    op: Literal["create", "update", "close"]
    id: int = Field(default=0, description="update/close: id існуючої мрії")
    text: str = Field(default="", description="create/update: сама мрія, коротко")
    status: Literal["fulfilled", "dropped", ""] = Field(
        default="", description="close: fulfilled — здійснилась, dropped — відпустили"
    )


class ReminderOp(BaseModel):
    op: Literal["create", "update", "cancel"]
    id: int = Field(default=0, description="update/cancel: id існуючого нагадування")
    text: str = Field(
        default="", description="create/update: текст нагадування, самодостатній, з часом події"
    )
    who: str = Field(default="", description="id людини, кому надіслати, або null — усім у сім'ї")
    at: str = Field(
        default="",
        description="коли надіслати, ISO 8601 з offset, напр. 2026-09-11T15:00:00+03:00;"
        " для повторюваного — найближчий раз",
    )
    repeat: str = Field(
        default="",
        description="daily — щодня, weekly — щотижня о тій самій годині; порожньо — один раз"
        " (update: не міняти); «-» більше не повторювати",
    )


# The one thing to do with a board is to replace its text, so there is no `op` field.
class TodayOp(BaseModel):
    member: str = Field(
        default="", description="чий список на сьогодні: id людини; порожньо — автора повідомлення"
    )
    text: str = Field(
        default="",
        description="повний новий текст списку одним реченням; порожньо — очистити список",
    )


# One page for the whole family, rewritten whole, so no `op` field either.
class NotesOp(BaseModel):
    text: str = Field(
        default="",
        description="повний новий текст сторінки «Нотатки» у Markdown; порожньо — очистити",
    )


class LlmResult(BaseModel):
    reply: str = Field(description="Коротка відповідь людині українською")
    items: list[ItemOp] = Field(default_factory=list)
    events: list[EventOp] = Field(default_factory=list)
    todos: list[TodoOp] = Field(default_factory=list)
    projects: list[ProjectOp] = Field(default_factory=list)
    dreams: list[DreamOp] = Field(default_factory=list)
    reminders: list[ReminderOp] = Field(default_factory=list)
    today: list[TodayOp] = Field(default_factory=list)
    notes: list[NotesOp] = Field(default_factory=list)


